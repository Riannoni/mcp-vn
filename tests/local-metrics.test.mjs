import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,readFile,writeFile,rm} from 'node:fs/promises';
import path from 'node:path';
import {tmpdir} from 'node:os';
const root=await mkdtemp(path.join(tmpdir(),'vn-local-metrics-'));
process.env.VN_DATA_DIR=root;
const store=await import('../src/game-store.mjs');
const local=await import('../src/local-scene.mjs');
test.after(()=>rm(root,{recursive:true,force:true}));
test('local episode exposes bounded completed-turn timings for readable statistics',async()=>{
 const g=await store.gameStart('ash-gate','Макс Кроу','Возраст: 34');
 await store.gameAction(g.id,'Привет',g.version);
 const ready=await store.gameNarrate({game_id:g.id,messages:[{speaker:'Мира',text:'Привет.'}],scene:{sprites:[{name:'Макс Кроу'},{name:'Мира'}]}});
 await local.beginLocalScene(g.id,ready.version);
 const file=path.join(root,'local-scenes',g.id+'.json');
 const doc=JSON.parse(await readFile(file));
 doc.sessions[0].metrics=[{request_id:'test-turn',overall_ms:1200}];
 await writeFile(file,JSON.stringify(doc));
 const ep=await local.getLocalEpisode(g.id);
 assert.deepEqual(ep.metrics,[{request_id:'test-turn',overall_ms:1200}]);
 const completed=await store.gameLocalTurnBegin(g.id,(await store.gameGet(g.id)).version);
 await store.gameLocalTurnComplete(g.id,completed.request_id);
 const failure=await store.gameLocalTurnBegin(g.id,(await store.gameGet(g.id)).version);
 await store.gameLocalTurnComplete(g.id,failure.request_id,{error:'temporary model error'});
 const session=doc.sessions[0];
 session.transcript=[{role:'player',request_id:completed.request_id,text:'Первый ход'},{role:'narrator',request_id:completed.request_id,text:'Ответ.'}];
 session.undo_stack=[structuredClone(session)];
 session.transcript.push({role:'player',request_id:failure.request_id,text:'Неотвеченный ход'});
 await writeFile(file,JSON.stringify(doc));
 await local.reviseLocalTurn(g.id,{version:(await store.gameGet(g.id)).version});
 assert.equal((await store.gameGet(g.id)).local_scene.turns,1,'undo of failed generation must not decrement completed turns');
});
